export function createDarkStyles(
  lightStyles: ReturnType<typeof createLightStyles>,
  darkPalette: StylePalette,
) {
  const darkColorMap: Record<string, string> = {
    '#ffffff': darkPalette.paper,
    '#fff': darkPalette.paper,
    '#eef3f7': darkPalette.background,
    '#183247': darkPalette.ink,
    '#667b8c': darkPalette.muted,
    '#d7e1e9': darkPalette.line,
    '#e8f4ec': darkPalette.greenSoft,
    '#eaf2f8': darkPalette.paleBlue,
    '#fff5db': darkPalette.amberSoft,
    '#fff0f0': darkPalette.redSoft,
    '#a86a00': darkPalette.amber,
    '#46546b': '#c5d0dc',
    '#98a5b8': '#8496aa',
    '#b8c9d7': '#465b70',
    '#edf0f5': darkPalette.line,
    '#f8faff': '#1c2c3f',
    '#f5f8fa': '#1b2b3d',
    '#eaf2fc': '#1c3046',
    '#fff7d8': '#40351d',
    '#fff0dc': '#422e20',
    '#fde7e8': '#42272d',
    '#d8e3eb': darkPalette.line,
    '#8692a5': '#a0afbf',
    '#8290a5': '#9caec0',
    '#7b889c': '#9eafc1',
    '#c9d6e0': '#3b5066',
    '#eef3fe': '#1b3046',
    '#dbe7ff': '#263d59',
    '#276844': '#8ad9aa',
    '#31664a': '#91d3a8',
    '#52678a': '#b3c3d8',
    '#aab6c8': '#aebdce',
    '#b9cbd9': '#546a80',
    '#c8d7e2': '#455a70',
    '#c8d8ff': '#354c70',
    '#c8e7d1': '#2a4d3a',
    '#d7e0ec': darkPalette.line,
    '#ddf5e6': '#183c2c',
    '#e5f7eb': '#193b2b',
    '#ebc6c8': '#5a3338',
    '#f0ced0': '#533137',
    '#075eaa': '#75afff',
    '#06477f': '#8abaff',
    '#18834b': '#63d18e',
    '#b83b42': '#f07b83',
  };
  const definitions: Record<string, Record<string, unknown>> = {};
  const accentBackgrounds: Record<string, string> = {
    '#075eaa': '#0c4b78',
    '#06477f': '#0b3d63',
    '#18834b': '#155d3c',
    '#b83b42': '#742c33',
    '#a86a00': '#754b00',
  };
  const accentText: Record<string, string> = {
    '#075eaa': '#75afff',
    '#06477f': '#8abaff',
    '#18834b': '#63d18e',
    '#b83b42': '#f07b83',
    '#a86a00': '#f0b954',
  };

  for (const [name, style] of Object.entries(lightStyles)) {
    const darkStyle: Record<string, unknown> = {};
    for (const [property, value] of Object.entries(
      style as Record<string, unknown>,
    )) {
      if (typeof value !== 'string') {
        darkStyle[property] = value;
        continue;
      }

      const color = value.toLowerCase();
      if (property === 'backgroundColor') {
        darkStyle[property] =
          accentBackgrounds[color] || darkColorMap[color] || value;
      } else if (property === 'color') {
        darkStyle[property] =
          color === '#fff' || color === '#ffffff'
            ? '#ffffff'
            : accentText[color] || darkColorMap[color] || value;
      } else if (property === 'borderColor') {
        darkStyle[property] =
          color === '#fff' || color === '#ffffff'
            ? darkPalette.line
            : darkColorMap[color] || value;
      } else if (property === 'shadowColor') {
        darkStyle[property] = '#000000';
      } else {
        darkStyle[property] = darkColorMap[color] || value;
      }
    }
    definitions[name] = darkStyle;
  }

  return StyleSheet.create(definitions) as ReturnType<typeof createLightStyles>;
}
